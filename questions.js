function getQuestions() {
  const stored = localStorage.getItem("sci_quest_questions");
  if (stored) {
    try {
      const parsed = JSON.parse(stored);
      let total = 0;
      for (const grade in parsed) {
        if (Array.isArray(parsed[grade])) {
          total += parsed[grade].length;
        }
      }
      if (total >= 200) {
        return parsed;
      }
      console.log(`Stored question database has only ${total} questions. Migrating to DEFAULT_QUESTIONS...`);
    } catch (e) {
      console.error("Error parsing stored questions", e);
    }
  }
  localStorage.setItem("sci_quest_questions", JSON.stringify(DEFAULT_QUESTIONS));
  return JSON.parse(JSON.stringify(DEFAULT_QUESTIONS));
}

function saveQuestions(questionsData) {
  localStorage.setItem("sci_quest_questions", JSON.stringify(questionsData));
  window.dispatchEvent(new CustomEvent("questions-updated", { detail: questionsData }));
}

function resetQuestionsToDefault() {
  localStorage.setItem("sci_quest_questions", JSON.stringify(DEFAULT_QUESTIONS));
  window.dispatchEvent(new CustomEvent("questions-updated", { detail: DEFAULT_QUESTIONS }));
  return JSON.parse(JSON.stringify(DEFAULT_QUESTIONS));
}

function updateSingleQuestion(grade, questionId, updatedObj) {
  const allQs = getQuestions();
  if (allQs[grade]) {
    const idx = allQs[grade].findIndex(q => q.id === questionId);
    if (idx !== -1) {
      allQs[grade][idx] = { ...allQs[grade][idx], ...updatedObj };
      saveQuestions(allQs);
      return true;
    }
  }
  return false;
}

function addQuestionToGrade(grade, questionObj) {
  const allQs = getQuestions();
  if (!allQs[grade]) {
    allQs[grade] = [];
  }
  
  const newId = `${grade}_${questionObj.difficulty || 'medium'}_${Date.now()}`;
  const completeObj = {
    id: newId,
    difficulty: questionObj.difficulty || "medium",
    topic: questionObj.topic || "วิทยาศาสตร์ทั่วไป",
    question: questionObj.question,
    options: questionObj.options || ["", "", "", ""],
    correct: parseInt(questionObj.correct) || 0,
    hint: questionObj.hint || "",
    reason: questionObj.reason || ""
  };
  
  allQs[grade].push(completeObj);
  saveQuestions(allQs);
  return completeObj;
}

function deleteQuestionFromGrade(grade, questionId) {
  const allQs = getQuestions();
  if (allQs[grade]) {
    const initialLen = allQs[grade].length;
    allQs[grade] = allQs[grade].filter(q => q.id !== questionId);
    if (allQs[grade].length !== initialLen) {
      saveQuestions(allQs);
      return true;
    }
  }
  return false;
}

window.ScienceDB = {
  getQuestions,
  saveQuestions,
  resetQuestionsToDefault,
  updateSingleQuestion,
  addQuestionToGrade,
  deleteQuestionFromGrade
};
